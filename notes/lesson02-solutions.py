# ===== 第 2 堂 練習參考解答（老師用）=====
import random

# --- 練習 1 --------------------------------------------------------
for i in range(10):
    print("⚔️ 攻擊！")

# --- 練習 2 --------------------------------------------------------
total = 0
for i in range(1, 11):
    exp = i * 15
    total = total + exp
    print(f"第 {i} 隻給 {exp} 點經驗")
print(f"總經驗 {total}")          # 825
# 常見錯：total = 0 寫進迴圈裡（結果會是 150）。
# 提示：「你希望歸零這件事發生幾次？」

# --- 練習 3 --------------------------------------------------------
prizes = ["金幣", "藥水", "寶石", "銘謝惠顧"]
for i in range(5):
    print(f"第 {i + 1} 次抽到：{random.choice(prizes)}")

# --- 練習 4 --------------------------------------------------------
hp = 100
hits = 0
while hp > 0:
    hits = hits + 1
    hp = hp - random.randint(8, 20)
print(f"打了 {hits} 下")           # 大約 7~9 下
# 常見錯：while hp <= 0（條件寫反，一次都不跑）。
# 提示：「這個條件是『繼續』還是『結束』？」

# --- 練習 5（挑戰）-------------------------------------------------
count = 0
for i in range(1000):
    if random.randint(1, 100) >= 95:
        count = count + 1
print(f"1000 次裡有 {count} 次 >= 95")
# 理論值 60 次（95~100 共 6 個數字，6%）。
# 多數人會猜 5% 或 50 次，很接近但不完全對 —— 正好可以聊「含頭含尾」。
