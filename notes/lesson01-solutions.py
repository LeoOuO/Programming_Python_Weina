# ===== 第 1 堂 練習參考解答（老師用，不要給學生）=====
# 每題附常見錯誤，提示時用「問問題」的方式，不要直接給程式碼。

# --- 練習 1 --------------------------------------------------------
name = "小雷"
job = "劍士"
hp = 100
atk = 18
print(f"{name} 是{job}，HP {hp} / ATK {atk}")
# 常見錯：用 + 接數字 → TypeError。提示：「你要接的是數字還是字？」

# --- 練習 2 --------------------------------------------------------
level = int(input("你的等級是多少？ "))
atk = 10 + level * 2
print(f"等級 {level} 的攻擊力是 {atk}")
# 常見錯：忘了 int()，算出來變成字串重複（"3" * 2 → "33"）。
# 提示：「你輸入的 3 現在是字還是數字？上次工坊那個錯誤訊息還記得嗎？」

# --- 練習 3 --------------------------------------------------------
hp = int(input("你現在的血量？ "))
if hp >= 70:
    print("狀態良好")
elif hp >= 30:
    print("小心一點")
else:
    print("快喝藥水！")
# 常見錯：順序寫反（30 寫在前面 → 永遠走到第一條）。
# 提示：「你輸入 90 的時候，第一條會不會成立？」

# --- 練習 4（挑戰）-------------------------------------------------
a_atk, a_def = 18, 5
b_atk, b_def = 14, 12
a_power = a_atk * 2 + a_def       # 41
b_power = b_atk * 2 + b_def       # 40
if a_power > b_power:
    print(f"A 比較強（{a_power} vs {b_power}）")
elif b_power > a_power:
    print(f"B 比較強（{b_power} vs {a_power}）")
else:
    print("平手")
# 多數學生會漏掉平手。問她：「如果兩邊剛好一樣呢？」
