# ===== 範例 1：做一張角色卡 =====
# 變數 = 有名字的盒子，裡面可以放「字」，也可以放「數字」

name = "小雷"          # 引號包起來的是「字串」（文字）
job = "劍士"
level = 3              # 沒有引號的是「整數」（數字）
hp = 100
atk = 18

print("=== 角色卡 ===")
print("名字：" + name)          # 字 + 字 = 接在一起
print("職業：" + job)
print("等級：", level)          # 逗號可以把不同東西印在同一行
print("血量：", hp)
print("攻擊：", atk)

# f-string：字串前面加一個 f，大括號裡面可以直接放變數，最常用
print(f"{name} 是 {level} 等的{job}，HP {hp}／ATK {atk}")

