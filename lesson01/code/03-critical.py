# ===== 範例 3：暴擊判定（if / elif / else）=====
# if 就是「如果」：條件成立才做縮排裡面的事

atk = 20
roll = int(input("擲一顆 100 面骰（輸入 1~100）： "))   # input 拿到的是字，要用 int() 變成數字

if roll >= 95:
    damage = atk * 3
    print("✨ 完美暴擊！傷害三倍")
elif roll >= 80:            # 上面不成立才檢查這一行
    damage = atk * 2
    print("💥 暴擊！傷害兩倍")
elif roll <= 5:
    damage = 0
    print("😵 失手了，完全沒打中")
else:                       # 前面都不成立
    damage = atk
    print("⚔️ 普通攻擊")

print(f"這一擊造成 {damage} 點傷害")

# 比較運算子： >  <  >=  <=  ==（等於） !=（不等於）
# 注意：判斷相等要用兩個等號 ==，一個等號 = 是「放進盒子」

