# ===== 範例 1：背包（清單 list）=====
# 清單 = 一排有順序的盒子，用中括號 [] 裝起來

bag = ["木劍", "紅藥水", "麵包"]

print(bag)                 # 整個清單印出來
print(len(bag))            # len() = 裡面有幾個東西

# 用「編號」拿出其中一個，編號從 0 開始！
print(f"第 1 格：{bag[0]}")
print(f"第 2 格：{bag[1]}")
print(f"最後一格：{bag[-1]}")     # -1 代表倒數第一個

# 撿到東西 → append（加到最後面）
bag.append("鐵劍")
print(f"撿到鐵劍，現在背包：{bag}")

# 用掉東西 → remove（拿掉指定的那個）
bag.remove("紅藥水")
print(f"喝掉藥水，現在背包：{bag}")

# 換掉某一格
bag[0] = "鋼劍"
print(f"換武器，現在背包：{bag}")

